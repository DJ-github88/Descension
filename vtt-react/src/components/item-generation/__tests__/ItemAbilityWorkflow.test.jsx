import React from 'react';
import { render, screen, fireEvent } from '@testing-library/react';
import '@testing-library/jest-dom';
import ItemWizard from '../ItemWizard';
import { itemAbilitySupport } from '../../../services/itemAuthoredAbility';
import { newItemAbility } from '../../../services/itemAuthoredAbility';
import ItemAbilityEditor from '../ItemAbilityEditor';
import { SpellLibraryStateContext } from '../../spellcrafting-wizard/context/SpellLibraryContext';
beforeAll(() => { Object.defineProperty(global, 'crypto', { value: require('crypto').webcrypto, configurable: true }); });
test('real ItemWizard compact edit requires Keep/Cancel; save/reopen preserves the whole ability and unknown item data', () => {
  const onComplete = jest.fn();
  const initial = { id: 'item-library', type: 'accessory', name: 'Witness Item', customStorage: { retain: true }, combatStats: { onHitEffects: { enabled: true, customEffects: [{ complex: 'manual' }] } } };
  const { unmount } = render(<ItemWizard initialData={initial} onComplete={onComplete} />);
  fireEvent.click(screen.getByRole('button', { name: /Basic/ }));
  fireEvent.click(screen.getByRole('button', { name: 'Add activated ability' }));
  fireEvent.change(screen.getByLabelText('Ability name'), { target: { value: 'Item Witness' } });
  expect(screen.getByRole('button', { name: /Next/ })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: /Appearance/ }));
  expect(screen.getByLabelText('Ability name')).toHaveValue('Item Witness');
  fireEvent.change(screen.getByLabelText('Effect'), { target: { value: 'healing' } });
  for (const label of ['AP price', 'Mana price', 'Range (ft)']) fireEvent.change(screen.getByLabelText(label), { target: { value: '0' } });
  fireEvent.click(screen.getByRole('button', { name: 'Keep ability on item' }));
  fireEvent.click(screen.getByRole('button', { name: /Appearance/ }));
  fireEvent.click(screen.getByRole('button', { name: /Create Item/ }));
  const saved = onComplete.mock.calls[0][0];
  expect(saved.customStorage).toEqual(initial.customStorage); expect(saved.combatStats.onHitEffects).toEqual(initial.combatStats.onHitEffects);
  expect(saved.authoredAbility.record.authoredDefinitionId).toMatch(/^[a-f0-9-]{36}$/);
  expect(itemAbilitySupport(saved.authoredAbility).definition).toMatchObject({ name: 'Item Witness', resourceCost: { actionPoints: 0, mana: 0 }, targeting: { rangeFeet: 0 } });
  unmount(); render(<ItemWizard initialData={JSON.parse(JSON.stringify(saved))} onComplete={onComplete} isEditing />);
  fireEvent.click(screen.getByRole('button', { name: /Basic/ })); fireEvent.click(screen.getByRole('button', { name: 'Edit activated ability' }));
  expect(screen.getByLabelText('Ability name')).toHaveValue('Item Witness'); expect(screen.getByLabelText('AP price')).toHaveValue(0);
  fireEvent.change(screen.getByLabelText('Ability name'), { target: { value: 'Cancelled' } }); fireEvent.click(screen.getByRole('button', { name: 'Cancel ability edit' }));
  fireEvent.click(screen.getByRole('button', { name: /Appearance/ })); fireEvent.click(screen.getByRole('button', { name: /Create Item/ }));
  expect(onComplete.mock.calls[1][0].authoredAbility).toEqual(saved.authoredAbility);
});
test('compatible library selection embeds a detached exact snapshot, not a mutable or name-resolved reference', () => {
  const record = { ...newItemAbility('d2398809-d3cf-4931-b8f6-24e5a382e1a5').record, id: 'library-spell' }, update = jest.fn();
  render(<SpellLibraryStateContext.Provider value={{ spells: [record] }}><ItemAbilityEditor itemData={{}} updateItemData={update} onEditingChange={() => {}} /></SpellLibraryStateContext.Provider>);
  fireEvent.change(screen.getByRole('combobox', { name: 'Compatible Spell Library definition' }), { target: { value: record.id } }); fireEvent.click(screen.getByRole('button', { name: 'Associate library snapshot' }));
  const association = update.mock.calls[0][0].authoredAbility; expect(association.record).toEqual(record); expect(association.record).not.toBe(record); expect(association.librarySpellId).toBe(record.id);
});
