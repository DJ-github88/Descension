export const getLevelOneSpellIcon = (spell) =>
    LEVEL_ONE_SPELL_ICON_OVERRIDES[spell?.id] || spell?.icon;

export const applyLevelOneSpellIcons = (spells) =>
    Array.isArray(spells)
        ? spells.map(spell => {
            const icon = getLevelOneSpellIcon(spell);
            return icon === spell.icon ? spell : { ...spell, icon };
        })
        : spells;
